/** Derive native field/enum admission and the wire schema from model and Host-only Zod definitions. */
import { readFile, writeFile } from 'node:fs/promises'
import { z } from 'zod'
import { NativeOnlyOperations, NativeResourceParameters, Request } from '../src/protocol.ts'

type Schema = ReturnType<typeof z.toJSONSchema>

function object(schema: Schema | boolean | undefined): Schema {
  if (schema === undefined || typeof schema === 'boolean') throw new Error('CUA protocol requires an object schema at this position')
  return schema
}
function variants(schema: Schema): Schema[] { return schema.anyOf ?? schema.oneOf ?? [schema] }

/**
 * Render deterministic native artifacts; platform actions and lifecycle remain handwritten.
 * @returns Native JSON Schema and Swift field/enum tables, including private continuations.
 */
export function renderNativeProtocol(): { json: string; swift: string } {
  const resources = new Map(Object.entries(NativeResourceParameters))
  const modelMethods = Request.options.map(schema => schema.shape.method.value).sort()
  const schemas = [...Request.options, ...NativeOnlyOperations].map(schema => z.toJSONSchema(schema))
  const fields = new Map<string, Set<string>>()
  const enums = new Map<string, Map<string, Set<string>>>()
  for (const schema of schemas) {
    const method = object(schema.properties?.method).const
    if (typeof method !== 'string') throw new Error('CUA method must be one string literal')
    const params = object(schema.properties?.params)
    const extension = resources.get(method)
    if (extension !== undefined) {
      const extra = z.toJSONSchema(extension)
      if (params.type !== 'object') throw new Error(`Host fields require object parameters: ${method}`)
      params.properties = { ...params.properties, ...extra.properties }
      params.required = [...new Set([...(params.required ?? []), ...(extra.required ?? [])])]
    }
    schema.properties = { id: { type: 'string' }, ...schema.properties }
    schema.required = ['id', 'method', 'params']
    delete schema.$schema
    const names = new Set<string>()
    const values = new Map<string, Set<string>>()
    for (const variant of variants(params)) {
      for (const [name, raw] of Object.entries(variant.properties ?? {})) {
        names.add(name)
        const property = object(raw)
        const item = property.type === 'array' && !Array.isArray(property.items) ? object(property.items) : property
        const allowed = item.enum?.filter((value): value is string => typeof value === 'string')
        if (allowed?.length) {
          const union = values.get(name) ?? new Set<string>()
          for (const value of allowed) union.add(value)
          values.set(name, union)
        }
      }
    }
    fields.set(method, names)
    if (values.size) enums.set(method, values)
  }
  const quoted = (values: Iterable<string>) => [...values].sort().map(value => JSON.stringify(value)).join(', ')
  const swift = [
    '// Generated by native/generate-protocol.ts from src/protocol.ts. Do not edit.',
    'enum NativeProtocol {',
    `    static let modelMethods: [String] = [${quoted(modelMethods)}]`,
    '    static let fields: [String: Set<String>] = [',
    ...[...fields].sort(([a], [b]) => a.localeCompare(b)).map(([method, names]) => `        ${JSON.stringify(method)}: [${quoted(names)}],`),
    '    ]',
    '    static let stringEnums: [String: [String: Set<String>]] = [',
    ...[...enums].sort(([a], [b]) => a.localeCompare(b)).map(([method, properties]) =>
      `        ${JSON.stringify(method)}: [${[...properties].sort(([a], [b]) => a.localeCompare(b))
        .map(([name, values]) => `${JSON.stringify(name)}: [${quoted(values)}]`).join(', ')}],`),
    '    ]',
    '}',
    '',
  ].join('\n')
  return { swift, json: JSON.stringify({
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $comment: 'Generated by native/generate-protocol.ts from src/protocol.ts. Do not edit.',
    title: 'dsh-cua native request',
    description: 'Host resource fields and private continuations are not model tool parameters. App handles and snapshots belong to one helper; coordinates are window-local macOS points.',
    oneOf: schemas,
  }, null, 2) + '\n' }
}

if (import.meta.main) {
  const generated = renderNativeProtocol()
  for (const [file, content] of [
    ['protocol.schema.json', generated.json], ['Sources/CuaNative/NativeProtocol.generated.swift', generated.swift],
  ]) {
    const path = new URL(file, import.meta.url)
    if (process.argv.includes('--check')) {
      if (await readFile(path, 'utf8') !== content) throw new Error(`Stale generated CUA protocol: ${file}`)
    } else await writeFile(path, content)
  }
}
